def generate_zip_fixture(dest: Path, entries: Optional[list] = None) -> FixtureResult:
    """Generate a minimal ZIP archive containing text entries."""
    import zipfile
    entries = entries or [
        ("file1.txt", b"Hello from fixture factory.\n"),
        ("data/file2.txt", b"Second fixture entry.\n"),
    ]
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, content in entries:
            zf.writestr(name, content)
    size = dest.stat().st_size
    return FixtureResult(
        fixture_type="ZIP",
        path=dest,
        size_bytes=size,
        strategy="programmatic",
        description=f"ZIP fixture with {len(entries)} entries",
        provenance={"source": "zipfile_module", "entries": [e[0] for e in entries]},
    )


# ── Internal PNG builder ─────────────────────────────────────────────────────

def _png_chunk(chunk_type: bytes, data: bytes) -> bytes:
    length = struct.pack(">I", len(data))
    crc = struct.pack(">I", zlib.crc32(chunk_type + data) & 0xFFFFFFFF)
    return length + chunk_type + data + crc


def _build_png(width: int, height: int, fill: tuple = (255, 255, 255)) -> bytes:
    """Build a minimal RGB PNG from scratch."""
    signature = b"\x89PNG\r\n\x1a\n"
    # IHDR: width, height, bit_depth=8, color_type=2 (RGB), compress=0, filter=0, interlace=0
    ihdr_data = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    ihdr = _png_chunk(b"IHDR", ihdr_data)
    # IDAT: raw scanlines with filter byte 0
    raw_rows = b""
    for _ in range(height):
        row = b"\x00" + bytes(fill) * width
        raw_rows += row
    compressed = zlib.compress(raw_rows)
    idat = _png_chunk(b"IDAT", compressed)
    iend = _png_chunk(b"IEND", b"")
    return signature + ihdr + idat + iend


def _build_barcode_png(width: int = 200, height: int = 60) -> bytes:
    """Build a PNG with vertical black/white stripes (barcode visual)."""
    signature = b"\x89PNG\r\n\x1a\n"
    ihdr_data = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    ihdr = _png_chunk(b"IHDR", ihdr_data)
    raw_rows = b""
    for y in range(height):
        row = b"\x00"
        for x in range(width):
            # Alternate black/white stripes every 4 pixels
            if (x // 4) % 3 == 1:
                row += b"\x00\x00\x00"  # black
            else:
                row += b"\xFF\xFF\xFF"  # white
        raw_rows += row
    compressed = zlib.compress(raw_rows)
    idat = _png_chunk(b"IDAT", compressed)
    iend = _png_chunk(b"IEND", b"")
    return signature + ihdr + idat + iend


def _build_bmp(width: int, height: int, r: int, g: int, b: int) -> bytes:
    """Build a minimal BMP file with solid fill color."""
    row_size = ((width * 3 + 3) // 4) * 4  # padded to 4 bytes
    pixel_data_size = row_size * height
    file_size = 54 + pixel_data_size
    # BMP file header (14 bytes)
    file_header = struct.pack("<2sIHHI", b"BM", file_size, 0, 0, 54)
    # DIB header (BITMAPINFOHEADER, 40 bytes)
    dib = struct.pack("<IiiHHIIiiII", 40, width, -height, 1, 24, 0, pixel_data_size, 2835, 2835, 0, 0)
    # Pixel data
    row = bytes([b, g, r]) * width  # BMP is BGR
    padding = b"\x00" * (row_size - width * 3)
    pixel_data = (row + padding) * height
    return file_header + dib + pixel_data
