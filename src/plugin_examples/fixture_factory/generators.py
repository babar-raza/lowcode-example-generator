@dataclass
class FixtureResult:
    fixture_type: str
    path: Optional[Path] = None
    size_bytes: int = 0
    strategy: str = "programmatic"
    description: str = ""
    provenance: dict = field(default_factory=dict)
    error: Optional[str] = None

    @property
    def success(self) -> bool:
        return self.error is None and self.path is not None and self.size_bytes > 0


def generate_minimal_png(dest: Path, width: int = 1, height: int = 1) -> FixtureResult:
    """Write a minimal valid PNG (white pixels) to dest."""
    if width == 1 and height == 1:
        data = base64.b64decode(_MINIMAL_1x1_WHITE_PNG_B64)
    elif width == 40 and height == 12:
        data = base64.b64decode(_MINIMAL_40x12_WHITE_PNG_B64)
    else:
        data = _build_png(width, height, fill=(255, 255, 255))
    dest.write_bytes(data)
    return FixtureResult(
        fixture_type="PNG",
        path=dest,
        size_bytes=len(data),
        strategy="programmatic",
        description=f"Minimal {width}x{height} white PNG",
        provenance={"source": "png_spec", "width": width, "height": height},
    )


