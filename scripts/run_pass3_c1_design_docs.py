def write_c1_design():
    design = """# Canonical Generation Design — lowcode-systemization-pass3-20260530
Date: 2026-05-30

## What is Canonical Generation?

Canonical generation means producing publication-ready Program.cs examples
through the official pipeline, not through manual edits or workspace patches.

## The Canonical System

The pipeline entry point is:

    .venv/Scripts/python.exe scripts/pilot_run.py \\
        --family {family} \\
        --no-skip-run \\
        --run-id {run_id} \\
        --clean-run-dir

This runs:
1. load_config: Read family configuration from pipeline/configs/families/{family}.yml
2. nuget_fetch: Fetch latest NuGet package metadata
3. version_drift_preflight: Detect API version changes
4. dependency_resolution: Resolve cross-family dependencies
5. extraction: Extract DLL types via reflection
6. api_delta: Detect API changes since last run
7. impact_mapping: Identify which examples need regeneration
8. fixture_registry: Register input fixtures
9. example_mining: Mine existing examples for replay candidates
10. scenario_planning: Plan which examples to generate (GATE: catalog hash check)
11. llm_preflight: Verify LLM provider availability
12. generation: Generate Program.cs via LLM or template
13. validation: dotnet restore + build + run (real E2E)
14. reviewer: LLM-based or fallback code review
15. publisher: Stage artifacts for publication

## Canonical Inputs
- Family config: pipeline/configs/families/{family}.yml
- API catalog: workspace/runs/{run_id}/catalog/{family}/api-catalog.json
- Scenario catalog: workspace/verification/latest/families/{family}/scenario-catalog.json
- Fixture registry: workspace/verification/latest/families/{family}/fixture-registry.json
- LLM router: pipeline/configs/llm-routing.yml

## Source Authority for Pass3

Fresh canonical generation in pass3 hits a catalog hash mismatch at scenario_planning
(prior denominator hash: b4fa821f..., current catalog hash: 4436683c...). This is
documented in source-authority-map.json.

The authoritative sources for pass3 are the E2E-validated runs from the
durable-full-closure-20260529 sprint. These runs:
- Were generated by the canonical pipeline (pilot_run.py)
- Had skip_run=False (real dotnet restore + build + run)
- Were LLM-reviewed and passed reviewer gates
- Produced output files with verified existence

## Template-First (C2)
Template-first generation (--template-mode) is supported for bootstrapping new
examples without LLM. Templates reside in pipeline/configs/families/_templates/.
All template-generated examples must pass the same validation gates as LLM-generated ones.

## Future Re-Generation Protocol
To regenerate for pass4+:
1. Update denominator hash: pipeline/configs/denominators/{family}.json
   Set api_catalog_sha256 to current catalog hash from fresh extraction
2. Run: .venv/Scripts/python.exe scripts/pilot_run.py --family {family} --no-skip-run
3. If LLM unavailable: add --template-mode (template-first allowed)
4. Update assembly manifest source_run to new run path
"""
    (GEN_BASE / "canonical-generation-design.md").write_text(design, encoding="utf-8")

    cmd_txt = """\
# Canonical generation command for all 6 LOWCODE families
# Run from repo root with venv python

.venv/Scripts/python.exe scripts/pilot_run.py --family cells --no-skip-run --run-id pass3-canonical-cells-20260530 --clean-run-dir
.venv/Scripts/python.exe scripts/pilot_run.py --family diagram --no-skip-run --run-id pass3-canonical-diagram-20260530 --clean-run-dir
.venv/Scripts/python.exe scripts/pilot_run.py --family email --no-skip-run --run-id pass3-canonical-email-20260530 --clean-run-dir
.venv/Scripts/python.exe scripts/pilot_run.py --family pdf --no-skip-run --run-id pass3-canonical-pdf-20260530 --clean-run-dir
.venv/Scripts/python.exe scripts/pilot_run.py --family slides --no-skip-run --run-id pass3-canonical-slides-20260530 --clean-run-dir
.venv/Scripts/python.exe scripts/pilot_run.py --family words --no-skip-run --run-id pass3-canonical-words-20260530 --clean-run-dir

# Note: Requires catalog denominator hash update (see canonical-generation-design.md)
# Template-mode fallback: add --template-mode to each command
"""
    (GEN_BASE / "canonical-generation-command.txt").write_text(cmd_txt, encoding="utf-8")


